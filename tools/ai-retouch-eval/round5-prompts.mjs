/* 12a 第五轮 · 四块口令(12e §二 腿 A)
 *
 * 店主原话:「**皮肤和指甲表面是两个东西,要分两种情况定基调去修**」。
 * 所以口令改成**四块固定结构,每块只说自己的宾语,块与块不许互相提及**:
 *   1【绝对不改】甲面/姿势/构图  2【甲面】  3【手部皮肤】  4【曝光】
 *
 * 🔴 一处按 §二 的结构要求处理并记入假设:
 *   旧 PREFIX 末句「肤色、白平衡、亮度的调整只作用于皮肤与背景,指甲区域的颜色、明暗、反光一律保持原样」
 *   **同时提到三个宾语**(肤色/白平衡/甲面),违反「每块只说自己的宾语」。
 *   拆法:「指甲区域…保持原样」归入【甲面】块(按宾语归属);
 *        「肤色、白平衡、亮度的调整只作用于皮肤与背景」**删掉** ——
 *        它原本是用来解 11z 那次「绝对不改甲色 vs 冷白皮」打架的补丁,
 *        而分块本身就是那个问题的结构性解法,补丁留着反而是跨块提及。
 *
 * 🔴 本轮唯一改动的旧句(§二-2):色温句的宾语从「整图」缩到「**甲面与背景**」——
 *   原因:它和新的手部冷白句在整图口径下必然打架。
 */
import { TONE_DARK, TONE_LIGHT, SUFFIX } from './round4-prompts.mjs'
export { SUFFIX }

/* ① 绝对不改 —— 只留甲面/姿势/构图句 */
export const BLOCK_KEEP = `这是一张美甲客照的保真修图任务。输出必须与原图是同一张照片、同一构图、同一双手、同一背景,只做下面要求的调整。
【绝对不改】指甲的形状、长度、颜色、图案、贴钻位置和数量与原图完全一致;手的姿势、手指位置、手指粗细、关节位置不改;背景内容和构图不改;画面比例与原图一致。`

/* ② 甲面 —— 深/浅甲句 + 缩了宾语的色温句 + 甲面保持句 */
export const NAIL_COLORTEMP = `甲面与背景的白平衡、色温以原图为准,保留原图本来的暖调,不做色温校正。指甲区域的颜色、明暗、反光一律保持原样。`
export const blockNail = (tone) => `【甲面】${tone === '深' ? TONE_DARK : TONE_LIGHT}${NAIL_COLORTEMP}`

/* ③ 手部皮肤 —— 店主 §二-3 原话直译,逐字 */
export const BLOCK_SKIN = `【手部皮肤】只针对手部皮肤,不含指甲:肤色统一、去掉痘印色斑倒刺等特殊瑕疵;皮肤轻度磨皮,保留指节和纹理的自然过渡,不许磨成塑料感;肤色比原图略偏冷白,干净通透,不许假白、不许发灰。`

/* ④ 曝光 —— 🔴 **只说曝光**,重写过,理由写在这里:
 *   沿用 EXPO_A_HAND/EXPO_B_HAND 会把三句别的宾语带进来 ——
 *   「清理皮肤上的杂质」(皮肤,与③重复)、「压掉甲面反光」(甲面,属②)、
 *   「白平衡以原图为准」(**整图口径的色温句,正是 §二-2 要缩成「甲面与背景」的那句**)。
 *   留着就直接跟③的「略偏冷白」打架,也违反「每块只说自己的宾语」。
 *   另:「空间感靠背景虚化」也删 —— 背景按 §七 是独立的最后一步,本轮口令不碰。
 *   D220(markdown 星号)按补二「下批修」在本轮一并去掉;这块本来就重写,不影响归因。
 */
export const EXPO_DARK = `这是一张暗调照片,不要整体提亮,原图的暗就是它该有的样子。只把最暗处的死黑轻轻抬一点点,抬到能看出纹理就停,阴影层次全部保留,画面整体的明暗关系不变。`
export const EXPO_NORMAL = `这张照片曝光正常,不要改变曝光。画面最亮的地方必须保留细节和层次,不允许出现成片的纯白。`
export const EXPO_BRIGHT = `这张照片偏亮,把过亮的地方压下来,找回最亮处的细节和层次,不允许出现成片的纯白。`
const EXPO = { A: EXPO_DARK, B: EXPO_NORMAL, C: EXPO_BRIGHT }
export const blockExpo = (bucket) => `【曝光】${EXPO[bucket]}`

export const promptR5 = (bucket, tone) =>
  BLOCK_KEEP + '\n' + blockNail(tone) + '\n' + BLOCK_SKIN + '\n' + blockExpo(bucket) + SUFFIX

/* ── 判据(§二 末 + §四)── */
export const MUST_PRESENT = {
  甲面块: ['【甲面】', '甲面与背景的白平衡、色温以原图为准', '指甲区域的颜色、明暗、反光一律保持原样'],
  手部块: ['【手部皮肤】', '只针对手部皮肤,不含指甲', '肤色比原图略偏冷白', '不许假白', '不许磨成塑料感'],
  曝光块: ['【曝光】'],
  不改块: ['【绝对不改】', '贴钻位置和数量与原图完全一致'],
}
/* §二:「甲面不许白 vs 手部冷白」允许共存(宾语不同),但两句各自的宾语词必须在 */
export const OBJECT_WORDS = { 甲面句: '指甲', 手部句: '手部皮肤' }
/* 跨块提及:这些词不许出现在【曝光】块里(它只管曝光) */
export const EXPO_MUST_GONE = ['真实纹理', '不做平涂', '不做美白平涂', '冷白', '白平衡', '色温', '清理皮肤', '甲面上杂乱', '背景轻微虚化', '*']

/* ═══════════ 12f §二 · 腿 A′:模型只留去瑕疵 ═══════════
 * 五轮验出的定律(12f §一-1):「冷」「白」「磨皮」「提亮」四类词,
 * **不论放在哪一块、宾语写得多窄,都会漏到整图** ——
 * 第五轮把「冷白」锁死在【手部皮肤】块,28 号照样全图漂蓝 −0.455。
 * 所以这一轮把手部块砍到**只剩去瑕疵**,验「模型不碰皮肤色调时,皮肤还会不会被它动」。
 */
export const BLOCK_SKIN_MIN = `【手部皮肤】只针对手部皮肤,不含指甲:去掉痘印、色斑、倒刺、细小杂质,其余一切保持原样。`
export const promptR5b = (bucket, tone) =>
  BLOCK_KEEP + '\n' + blockNail(tone) + '\n' + BLOCK_SKIN_MIN + '\n' + blockExpo(bucket) + SUFFIX

/* §二:六词黑名单。
 * 🔴 令说「全文 grep 不到」,但同时说【甲面】【曝光】原样 —— **两者不能同时成立**:
 *   剩下的「白/提亮/通透」全在那两块里,而且全是**否定式护栏**(「甲面不许提亮」「不许变白变浊」
 *   「白平衡以原图为准」),不是在请求那个效果;砍掉等于把 §一-2 认定有正作用的那组护栏也砍掉。
 *   取法:黑名单**只作用于【手部皮肤】块**(六词本来就是冲着手部块去的);
 *   全文命中位置另行列出供店主裁。 */
export const R5B_BLACKLIST = ['冷', '白', '磨皮', '提亮', '通透', '干净']
export const R5B_BLACKLIST_SCOPE = '【手部皮肤】块'
/** 全文里六词各出现在哪一块 —— 给店主看的,不做判据 */
export const blacklistHits = (bucket, tone) => {
  const blocks = { 绝对不改: BLOCK_KEEP, 甲面: blockNail(tone), 手部皮肤: BLOCK_SKIN_MIN, 曝光: blockExpo(bucket), 输出: SUFFIX }
  return R5B_BLACKLIST.map((w) => ({ 词: w, 出现在: Object.entries(blocks).filter(([, v]) => v.includes(w)).map(([k]) => k) }))
    .filter((x) => x.出现在.length)
}
