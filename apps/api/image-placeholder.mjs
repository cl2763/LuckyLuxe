/* 占位零回落(店主 2026-08-28 六立律,全局)。

   **店主原话就是规格**:
   > 「只要没有上传过的图片,在图片占位的地方都应该显示一个图片占位,或者就是那种有一个小相机的
   >   那种空白页面,让人感受到这里应该是有图片的,只是他没有上传而已。」

   **律**:凡展示图片的位置,没配图时一律显示「占位」——空框 + 相机图标 + 一句「还没有图片」。
   **不许回落到任何别的租户的图,也不许什么都不显示。** 三态各有各的样子:
     有图 / 没配图=占位 / 不该有图=整块不出现。

   🔴 病根不在渲染层,在**写入层**:建项目时 `imageUrl` 默认塞 `/assets/images/nail-addon.jpg`
   (店主本店那张美甲工具照)——**小婕店 29 个项目全挂着它**,走查店也是。
   渲染层再怎么改都没用,因为库里存的就是别人家的图。

   **「上传过」怎么定义**(这条是判据的地基,必须能证伪):
   `/assets/...` 是**平台自带资产**,商家上传的是 `data:` 或 `https://` ——
   所以**凡以 `/assets/` 开头的内容图,一律等于"没人上传过"**,出占位。
   这条对所有租户一视同仁,包括旗舰店(她本店那几张也是种子图,不是她传的)。

   适用范围(**内容图**,商家可上传的那些):项目图 / 加项图 / 门店封面 / 顾客头像 / 作品图 / 轮播。
   **不适用**:界面图标、Logo、tabbar、登录页背景 —— 那是产品外观,不是商家内容。 */
export function isOwnUpload(url) {
  const s = String(url || '').trim()
  if (!s) return false
  return s.startsWith('data:image/') || s.startsWith('https://') || s.startsWith('http://')
}

/* 内容图的唯一出口:商家自己传的原样给,平台自带资产与空值一律回空串 → 两端出占位。
   为什么统一在后端出:**顾客可见的图源只有一处真相**,前端零判断、零回落(假数回落红线第 3 条)。 */
export function contentImage(url) {
  return isOwnUpload(url) ? String(url).trim() : ''
}
