const assert = require('node:assert/strict')
const {sceneFromScan,memberCodeFromScan}=require('./scan-code')
assert.equal(memberCodeFromScan({path:'pages/scan-entry/index?scene=mOAICUST7',result:''}),'LL-OAICUST7')
assert.equal(memberCodeFromScan({result:'mAICUST14'}),'LL-AICUST14')
assert.equal(memberCodeFromScan({result:'LL-AICUST14'}),'LL-AICUST14')
assert.equal(memberCodeFromScan({result:'https://x.test/pages/scan-entry/index?scene=mAICUST14'}),'LL-AICUST14')
assert.equal(sceneFromScan({path:'pages/scan-entry/index?scene=s1234567890abcdef12345678'}),'s1234567890abcdef12345678')
assert.equal(sceneFromScan({result:'https://x.test/sign?t=sg_1234567890abcdef12345678'+ 'a'.repeat(40)}),'s1234567890abcdef12345678')
assert.equal(sceneFromScan({result:'garbage'}),'')
assert.equal(memberCodeFromScan({result:'garbage'}),'')
console.log('ok: WeChat path, scene, QR URL, plain member code and invalid input')
